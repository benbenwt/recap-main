impl From<device_query::MouseButton> for crate::Button {
    fn from(value: device_query::MouseButton) -> Self {
        match value {
            1 => crate::Button::Left,
            2 => crate::Button::Right,
            3 => crate::Button::Middle,
            value => crate::Button::Unknown(value as u8),
        }
    }
}

impl From<crate::Button> for device_query::MouseButton {
    fn from(value: crate::Button) -> Self {
        match value {
            crate::Button::Left => 1,
            crate::Button::Right => 2,
            crate::Button::Middle => 3,
            crate::Button::Unknown(value) => value as usize,
        }
    }
}
